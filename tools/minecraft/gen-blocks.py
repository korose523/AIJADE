#!/usr/bin/env python3
"""Writes src/Aijade.Integrations/Minecraft/McBlocks.g.cs from the block report of the official server.

Generate the report with the server jar (no world is created):
    java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports --output <dir>
then:  tools/minecraft/gen-blocks.py <dir>/reports/blocks.json

Block states of one block are contiguous, so the table stores each block's first state id; a state's block is the last
entry whose first state is not greater than it.
"""
import json
import os
import sys

blocks = json.load(open(sys.argv[1], encoding="utf-8"))
ranges = []
for name, b in blocks.items():
    ids = sorted(s["id"] for s in b["states"])
    assert ids == list(range(ids[0], ids[-1] + 1)), name
    ranges.append((ids[0], name.removeprefix("minecraft:")))
ranges.sort()
out = os.path.join(os.path.dirname(__file__), "..", "..", "src", "Aijade.Integrations", "Minecraft", "McBlocks.g.cs")
lines = ["// <auto-generated> by tools/minecraft/gen-blocks.py from the 26.3 server's data report (blocks.json). Do not edit.",
         "namespace Aijade.Integrations.Minecraft;", "", "public static partial class McBlocks", "{",
         "    /// <summary>The first block-state id of each block, ascending.</summary>",
         "    private static readonly int[] FirstState =", "    ["]
for i in range(0, len(ranges), 12):
    lines.append("        " + " ".join(f"{r[0]}," for r in ranges[i:i + 12]))
lines += ["    ];", "", "    /// <summary>Block names (without the minecraft: namespace), parallel to FirstState.</summary>",
          "    private static readonly string[] Names =", "    ["]
for i in range(0, len(ranges), 6):
    lines.append("        " + " ".join(f'"{r[1]}",' for r in ranges[i:i + 6]))
lines += ["    ];", "}", ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(f"{len(ranges)} blocks -> {os.path.normpath(out)}")
