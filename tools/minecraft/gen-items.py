#!/usr/bin/env python3
"""Writes src/Aijade.Integrations/Minecraft/McItems.g.cs from the item registry of the official server's data report.

Generate the report with the server jar (no world is created):
    java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports --output <dir>
then:  tools/minecraft/gen-items.py <dir>/reports/registries.json
"""
import json
import os
import sys

reg = json.load(open(sys.argv[1], encoding="utf-8"))["minecraft:item"]["entries"]
names = [k.removeprefix("minecraft:") for k, _ in sorted(reg.items(), key=lambda kv: kv[1]["protocol_id"])]
assert [reg["minecraft:" + n]["protocol_id"] for n in names] == list(range(len(names)))
out = os.path.join(os.path.dirname(__file__), "..", "..", "src", "Aijade.Integrations", "Minecraft", "McItems.g.cs")
lines = ["// <auto-generated> by tools/minecraft/gen-items.py from the 26.3 server's data report (registries.json). Do not edit.",
         "namespace Aijade.Integrations.Minecraft;", "", "public static partial class McItems", "{",
         "    /// <summary>Item names (without the minecraft: namespace) indexed by protocol id.</summary>",
         "    public static readonly string[] Names =", "    ["]
for i in range(0, len(names), 6):
    lines.append("        " + " ".join(f'"{n}",' for n in names[i:i + 6]))
lines += ["    ];", "}", ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(f"{len(names)} items -> {os.path.normpath(out)}")
