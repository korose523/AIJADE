#!/bin/bash
set -euo pipefail
AIJADE_LOCAL_ROOT="/Volumes/Untitled/AIJADE"
AIJADE_RUNTIME_ROOT="$AIJADE_LOCAL_ROOT/.runtime"
if [[ -d "$AIJADE_LOCAL_ROOT/.runtime/posix/colima/default" ]]; then
  AIJADE_RUNTIME_ROOT="$AIJADE_LOCAL_ROOT/.runtime/posix"
fi
export AIJADE_RUNTIME_ROOT
export AIJADE_WORKSPACE_ROOT="$AIJADE_LOCAL_ROOT"
export AIJADE_DOTNET_BIN="${AIJADE_DOTNET_BIN:-/Users/mac/.dotnet/dotnet}"
export DOTNET_ROOT="$(dirname -- "$AIJADE_DOTNET_BIN")"
export PATH="$DOTNET_ROOT:$PATH"
export AIJADE_ARTIFACTS="${AIJADE_ARTIFACTS:-$AIJADE_RUNTIME_ROOT/build-artifacts/aijade-next}"
export AIJADE_DATA_DIR="${AIJADE_DATA_DIR:-$AIJADE_LOCAL_ROOT/.research/imported-local-share/aijade-data}"
export TMPDIR="$AIJADE_RUNTIME_ROOT/tmp/"
export TMP="$TMPDIR" TEMP="$TMPDIR"
export XDG_CACHE_HOME="$AIJADE_RUNTIME_ROOT/cache"
export PYTHONDONTWRITEBYTECODE=1
export PYTHONPYCACHEPREFIX="$XDG_CACHE_HOME/python"
export MPLCONFIGDIR="$XDG_CACHE_HOME/matplotlib"
export CLANG_MODULE_CACHE_PATH="$XDG_CACHE_HOME/clang-modules"
export SWIFT_MODULECACHE_PATH="$XDG_CACHE_HOME/swift-modules"
export UV_CACHE_DIR="$XDG_CACHE_HOME/uv"
export HF_HOME="$XDG_CACHE_HOME/huggingface"
export TORCH_HOME="$XDG_CACHE_HOME/torch"
export NPM_CONFIG_CACHE="$XDG_CACHE_HOME/npm"
export PLAYWRIGHT_BROWSERS_PATH="$XDG_CACHE_HOME/playwright-browsers"
export NUGET_PACKAGES="$AIJADE_RUNTIME_ROOT/nuget/packages"
export NUGET_HTTP_CACHE_PATH="$XDG_CACHE_HOME/nuget-http"
export DOTNET_CLI_HOME="$AIJADE_RUNTIME_ROOT/dotnet-home"
export DOTNET_CLI_TELEMETRY_OPTOUT=1
export DOTNET_CLI_USE_MSBUILD_SERVER=0
export MSBUILDDISABLENODEREUSE=1
export UseSharedCompilation=false
export DOTNET_PROCESSOR_COUNT=2
AIJADE_SERVICE_STATE_ROOT="$AIJADE_RUNTIME_ROOT"
export AIJADE_SERVICE_STATE_ROOT
export COLIMA_HOME="$AIJADE_SERVICE_STATE_ROOT/colima"
export COLIMA_CACHE_HOME="$XDG_CACHE_HOME/colima"
export LIMA_HOME="$AIJADE_SERVICE_STATE_ROOT/lima"
export DOCKER_CONFIG="$AIJADE_LOCAL_ROOT/.runtime/docker"
export OLLAMA_MODELS="$AIJADE_LOCAL_ROOT/.runtime/ollama-models"
mkdir -p "$TMPDIR" "$XDG_CACHE_HOME" "$NUGET_PACKAGES" "$DOTNET_CLI_HOME" "$DOCKER_CONFIG" "$COLIMA_HOME" "$LIMA_HOME"
case "$PWD" in
  "$AIJADE_LOCAL_ROOT"|"$AIJADE_LOCAL_ROOT"/*) ;;
  *) cd "$AIJADE_LOCAL_ROOT" ;;
esac
exec "$@"
