#!/usr/bin/env python3
"""Per-case paths of the 40-pair held-out comparison through both rounds under C1 and C2 (thesis Table 7.5).

Requested by the supervisor on 23 November 2026: the Measures paragraph of Section 7.3 promised the full path of each
case through both rounds under both conditions. This script only reads the four score files of the complete second run
(results/heldout-02/score-02-block-{1..4}.json); it runs no model, no renderer and no database, and changes no record.

Usage: case_paths.py [--out-json FILE] [--out-md FILE]
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCORES = [HERE / "results" / "heldout-02" / f"score-02-block-{b}.json" for b in range(1, 5)]
# Window names of the fixed contract and the case labels of the development cases (paired-development-scoring-v1.json).
LABELS = {
    "none": "H", "execution_receipt_intent": "I1", "asset_admission": "I2", "duplicate_invocation_2": "I3",
    "execution_unknown": "I4", "execution_failed": "I5", "claimed_receipt_stage": "I6",
    "revocation_before_round2": "I7", "post_promotion_authority_write": "I8", "wrong_allowed_act_in_round1": "S1",
}
FIELDS = ("promotionServiceEntries", "persistedSpecs", "authorityState", "invalidDurablePromotions",
          "actualRound2Queries", "retrievedRound2Queries", "round2SandboxExecutions", "integrityInvalidReuse",
          "outcomeMemories", "deliveryStatus", "databaseError")


def round1(c):
    if c["persistedSpecs"] == 0:
        return f"not promoted; authority {c['authorityState']}"
    wrong = " (wrong)" if c["invalidDurablePromotions"] else ""
    return f"promoted{wrong}; authority {c['authorityState']}"


def round2(c):
    if c["retrievedRound2Queries"] == 0:
        return "nothing retrieved; not reused"
    if c["round2SandboxExecutions"] == 0:
        return "retrieved; not reused"
    wrong = " (wrong)" if c["integrityInvalidReuse"] else ""
    return f"retrieved; reused{wrong} ({c['round2SandboxExecutions']} execution of {c['actualRound2Queries']} queries)"


def build():
    cases = []
    for block, path in enumerate(SCORES, 1):
        score = json.loads(path.read_text(encoding="utf-8"))
        arms = {arm: {c["caseId"]: c for c in score["arms"][arm]["byCase"]} for arm in ("C1", "C2")}
        for case_id, c1 in arms["C1"].items():
            c2 = arms["C2"][case_id]
            assert c1["window"] == c2["window"]
            cases.append({
                "block": block, "caseId": case_id, "window": c1["window"], "label": LABELS[c1["window"]],
                "category": c1["category"],
                "C1": {"round1": round1(c1), "round2": round2(c1), **{f: c1[f] for f in FIELDS}},
                "C2": {"round1": round1(c2), "round2": round2(c2), **{f: c2[f] for f in FIELDS}},
            })
    totals = {arm: {"wrongPromotions": sum(c[arm]["invalidDurablePromotions"] for c in cases),
                    "wrongReuses": sum(c[arm]["integrityInvalidReuse"] for c in cases)} for arm in ("C1", "C2")}
    carried = sum(1 for c in cases if c["C1"]["invalidDurablePromotions"] and c["C1"]["integrityInvalidReuse"])
    reuse_without_c1_promotion = sum(1 for c in cases if c["C1"]["integrityInvalidReuse"] and not c["C1"]["invalidDurablePromotions"])
    stopped_in_round2_only_by_c2 = sum(1 for c in cases if c["C1"]["integrityInvalidReuse"] and not c["C2"]["integrityInvalidReuse"]
                                       and not c["C1"]["invalidDurablePromotions"])
    return {
        "schema": "aijade.ch7.heldout-case-paths.v1",
        "source": [str(p.relative_to(HERE)) for p in SCORES],
        "cases": cases,
        "totals": totals,
        "propagation": {
            "c1WrongPromotionsReusedInRound2": carried,
            "c1WrongReusesWithoutAC1WrongPromotion": reuse_without_c1_promotion,
            "casesStoppedInRound2ByC2AndMissedByC1": stopped_in_round2_only_by_c2,
        },
        "note": "Finite constructed cases; no population rate. Round-2 semantic correctness is not measured.",
    }


def markdown(report):
    lines = ["# Held-out case paths (40 pairs, both rounds, C1 and C2)", "",
             "Generated by `case_paths.py` from the score files of the complete second run. Thesis Table 7.5 groups these rows by case type.", "",
             "| Block | Case | Type | C1 round 1 | C1 round 2 | C2 round 1 | C2 round 2 |", "|---|---|---|---|---|---|---|"]
    for c in report["cases"]:
        lines.append(f"| {c['block']} | `{c['caseId']}` | {c['label']} ({c['window']}) | {c['C1']['round1']} | {c['C1']['round2']} | "
                     f"{c['C2']['round1']} | {c['C2']['round2']} |")
    t, p = report["totals"], report["propagation"]
    lines += ["", f"C1: {t['C1']['wrongPromotions']} wrong promotions, {t['C1']['wrongReuses']} wrong reuses; "
              f"C2: {t['C2']['wrongPromotions']} and {t['C2']['wrongReuses']}. "
              f"C1 wrong promotions reused in round 2: {p['c1WrongPromotionsReusedInRound2']}. "
              f"Cases stopped in round 2 by C2 and missed by C1: {p['casesStoppedInRound2ByC2AndMissedByC1']}.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out-json", default=str(HERE / "case-paths.json"))
    parser.add_argument("--out-md", default=str(HERE / "case-paths.md"))
    args = parser.parse_args()
    report = build()
    Path(args.out_json).write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    Path(args.out_md).write_text(markdown(report), encoding="utf-8")
    print(json.dumps({"totals": report["totals"], "propagation": report["propagation"]}))


if __name__ == "__main__":
    main()
